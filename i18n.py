def get_t(lang: str = 'fr'):
    """Return a translation function for the given language."""
    def t(key: str) -> str:
        entry = TRANSLATIONS.get(key)
        if entry is None:
            return key
        return entry.get(lang, entry.get('fr', key))
    return t
